export interface GoogleIconProps extends React.SVGProps<SVGSVGElement> {
  name: string
  className?: string
  size?: number | string
  filled?: boolean
}

export function GoogleIcon({
  name,
  className = "",
  size = 18,
  filled = false,
  style,
  ...props
}: GoogleIconProps) {
  const IconComponent = ICON_MAP[name] || HelpCircle

  const numericSize =
    typeof size === "number" ? size : parseInt(String(size), 10) || 18

  return (
    <IconComponent
      size={numericSize}
      className={`shrink-0 ${className}`}
      fill={filled ? "currentColor" : "none"}
      style={style}
      aria-hidden="true"
      {...props}
    />
  )
}
